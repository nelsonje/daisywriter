"""Read a Word (.docx) template into the paragraph model.

Only the main document body is read; page headers and footers are ignored
(letterhead is assumed to be pre-printed). Formatting is reduced to what a
typewriter can do: bold, underline, alignment, indents and blank-line spacing.
"""
from __future__ import annotations

import re
from pathlib import Path

import docx
from docx.oxml.ns import qn

from . import issues as I
from .model import Align, FieldRef, Paragraph, Span, Template

TWIPS_PER_PT = 20

# Fields whose visible result is kept as ordinary text.
KEEP_RESULT_FIELDS = {"HYPERLINK", "REF", "PAGEREF", "NOTEREF", "SYMBOL", "QUOTE", "STYLEREF",
                      "DOCPROPERTY", "TITLE", "AUTHOR", "SUBJECT", "INCLUDETEXT", "SEQ"}
# Page numbering is generated by daisywriter, because Word's pages won't match.
PAGE_FIELDS = {"PAGE", "NUMPAGES", "SECTIONPAGES"}
DATE_FIELDS = {"DATE", "CREATEDATE", "SAVEDATE", "PRINTDATE", "TIME"}

CASE_SWITCHES = {"upper": "upper", "lower": "lower", "caps": "caps", "firstcap": "firstcap"}

# {{ Name }}, {{ Name:picture }}, {{body}}, {{/body}}, or typed «Name»
PLACEHOLDER = re.compile(r"\{\{\s*(?P<inner>[^{}]+?)\s*\}\}|«(?P<guil>[^«»{}]+)»")


def load_template(path: str | Path) -> Template:
    return _Reader(Path(path)).read()


# ---------------------------------------------------------------- styles

def _on(el) -> bool:
    """Value of an OOXML on/off property element (w:b, w:keepNext, ...)."""
    if el is None:
        return False
    return el.get(qn("w:val"), "true").lower() not in ("0", "false", "off", "none")


class _Styles:
    def __init__(self, document):
        root = document.styles.element
        self.by_id = {s.get(qn("w:styleId")): s for s in root.findall(qn("w:style"))}
        self.default_para = None
        for s in root.findall(qn("w:style")):
            if s.get(qn("w:type")) == "paragraph" and s.get(qn("w:default")) in ("1", "true", "on"):
                self.default_para = s.get(qn("w:styleId"))
        dd = root.find(qn("w:docDefaults"))
        self.ppr_default = dd.find(f"{qn('w:pPrDefault')}/{qn('w:pPr')}") if dd is not None else None
        self.rpr_default = dd.find(f"{qn('w:rPrDefault')}/{qn('w:rPr')}") if dd is not None else None

    def chain(self, style_id):
        seen = set()
        while style_id and style_id not in seen and style_id in self.by_id:
            seen.add(style_id)
            s = self.by_id[style_id]
            yield s
            based = s.find(qn("w:basedOn"))
            style_id = based.get(qn("w:val")) if based is not None else None

    def para_style_id(self, p_el):
        ppr = p_el.find(qn("w:pPr"))
        ps = ppr.find(qn("w:pStyle")) if ppr is not None else None
        return ps.get(qn("w:val")) if ps is not None else self.default_para

    def ppr_chain(self, p_el) -> list:
        out = [p_el.find(qn("w:pPr"))]
        out += [s.find(qn("w:pPr")) for s in self.chain(self.para_style_id(p_el))]
        out.append(self.ppr_default)
        return [e for e in out if e is not None]

    def rpr_chain(self, r_el, p_el) -> list:
        rpr = r_el.find(qn("w:rPr"))
        out = [rpr]
        rs = rpr.find(qn("w:rStyle")) if rpr is not None else None
        if rs is not None:
            out += [s.find(qn("w:rPr")) for s in self.chain(rs.get(qn("w:val")))]
        out += [s.find(qn("w:rPr")) for s in self.chain(self.para_style_id(p_el))]
        out.append(self.rpr_default)
        return [e for e in out if e is not None]


def _first(chain, tag):
    for el in chain:
        found = el.find(qn(tag))
        if found is not None:
            return found
    return None


def _attr_pt(chain, tag, *attrs) -> float | None:
    """First value of any of attrs on the first element in chain that has it, in points."""
    for el in chain:
        found = el.find(qn(tag))
        if found is None:
            continue
        for a in attrs:
            v = found.get(qn(a))
            if v is not None:
                try:
                    return int(v) / TWIPS_PER_PT
                except ValueError:
                    pass
    return None


# ---------------------------------------------------------------- fields

def _tokens(instr: str) -> list[str]:
    return [m.group(1) if m.group(1) is not None else m.group(2)
            for m in re.finditer(r'"([^"]*)"|(\S+)', instr)]


def parse_field_instruction(instr: str) -> tuple[str, FieldRef | None]:
    """Return (field type, FieldRef for MERGEFIELD/DATE fields)."""
    toks = _tokens(instr)
    if not toks:
        return "", None
    kind = toks[0].upper()
    if kind not in ("MERGEFIELD",) and kind not in DATE_FIELDS:
        return kind, None
    name = None
    picture = pic_kind = case = None
    before = after = ""
    i = 1
    while i < len(toks):
        t = toks[i]
        arg = toks[i + 1] if i + 1 < len(toks) else ""
        if t == "\\*":
            c = CASE_SWITCHES.get(arg.lower())
            if c:
                case = c
            i += 2
        elif t == "\\@":
            picture, pic_kind = arg, "date"
            i += 2
        elif t == "\\#":
            picture, pic_kind = arg, "number"
            i += 2
        elif t == "\\b":
            before = arg
            i += 2
        elif t == "\\f":
            after = arg
            i += 2
        elif t.startswith("\\"):
            i += 1
        else:
            if name is None:
                name = t
            i += 1
    if kind == "MERGEFIELD":
        if not name:
            return kind, None
        return kind, FieldRef(name, picture, pic_kind, case, before, after, "mergefield")
    return kind, FieldRef("Today", picture, "date", case, source="date")


# ---------------------------------------------------------------- placeholders

def _placeholder_ref(inner: str) -> tuple[str | None, FieldRef | None]:
    """Return (marker, FieldRef) for the inside of {{ ... }}."""
    compact = re.sub(r"\s+", "", inner).lower()
    if compact in ("body", "/body"):
        return compact, None
    name, _, pic = inner.partition(":")
    name, pic = name.strip(), pic.strip() or None
    case = None
    if pic and pic.lower() in CASE_SWITCHES:
        case, pic = CASE_SWITCHES[pic.lower()], None
    return None, FieldRef(name, pic, None, case, source="placeholder")


def split_placeholders(spans: list[Span]) -> list[Span]:
    """Find placeholders in runs of plain text spans, even across formatting runs."""
    out: list[Span] = []
    group: list[Span] = []

    def flush():
        if not group:
            return
        text = "".join(s.text for s in group)
        attrs = [(s.bold, s.underline) for s in group for _ in s.text]
        pos = 0

        def emit_text(a, b):
            j = a
            while j < b:
                k = j
                while k < b and attrs[k] == attrs[j]:
                    k += 1
                out.append(Span(text[j:k], bold=attrs[j][0], underline=attrs[j][1]))
                j = k

        for m in PLACEHOLDER.finditer(text):
            emit_text(pos, m.start())
            inner = m.group("inner") if m.group("inner") is not None else m.group("guil")
            marker, ref = _placeholder_ref(inner)
            b, u = attrs[m.start()]
            out.append(Span(marker=marker, field=ref, bold=b, underline=u))
            pos = m.end()
        emit_text(pos, len(text))
        group.clear()

    for s in spans:
        if s.field is None and s.marker is None:
            group.append(s)
        else:
            flush()
            out.append(s)
    flush()
    return out


def _merge_adjacent(spans: list[Span]) -> list[Span]:
    out: list[Span] = []
    for s in spans:
        if (out and s.field is None and s.marker is None and out[-1].field is None
                and out[-1].marker is None and (out[-1].bold, out[-1].underline) == (s.bold, s.underline)):
            out[-1] = Span(out[-1].text + s.text, s.bold, s.underline)
        elif s.field is not None or s.marker is not None or s.text:
            out.append(s)
    return out


# ---------------------------------------------------------------- reader

class _Reader:
    def __init__(self, path: Path):
        self.path = path
        self.issues: list[I.Issue] = []
        self._noted: set[str] = set()

    def note(self, key: str, issue: I.Issue):
        """Report an issue once per document."""
        if key not in self._noted:
            self._noted.add(key)
            self.issues.append(issue)

    def read(self) -> Template:
        try:
            document = docx.Document(str(self.path))
        except Exception as e:  # python-docx raises several types for bad files
            raise ValueError(f"{self.path.name} isn't a readable Word .docx file ({e})") from e
        self.styles = _Styles(document)
        self.default_tab_pt = 36.0
        dts = document.settings.element.find(qn("w:defaultTabStop"))
        if dts is not None and dts.get(qn("w:val"), "").isdigit() and int(dts.get(qn("w:val"))) > 0:
            self.default_tab_pt = int(dts.get(qn("w:val"))) / TWIPS_PER_PT
        self.paragraphs: list[Paragraph] = []
        self._check_sections(document)
        self._walk_blocks(document.element.body)
        for p in self.paragraphs:
            if "{{" in p.text.replace("{{body}}", "").replace("{{/body}}", "") or "}}" in p.text:
                self.issues.append(I.warning(
                    "has '{{' or '}}' that isn't a complete placeholder; check for a typo",
                    f"paragraph {p.index}"))
        return Template(str(self.path), self.paragraphs, self.issues)

    def _check_sections(self, document):
        for section in document.sections:
            cols = section._sectPr.find(qn("w:cols"))
            if cols is not None and int(cols.get(qn("w:num"), "1")) > 1:
                self.note("columns", I.error("multiple text columns can't be typed", "template"))
            parts = [section.header, section.footer, section.first_page_header,
                     section.first_page_footer, section.even_page_header, section.even_page_footer]
            for part in parts:
                if not part.is_linked_to_previous and any(p.text.strip() for p in part.paragraphs):
                    self.note("headers", I.info(
                        "the page header/footer is ignored; only the document body is typed "
                        "(page numbers can be generated instead)", "template"))

    def _walk_blocks(self, parent):
        for el in parent.iterchildren():
            if el.tag == qn("w:p"):
                self._paragraph(el)
            elif el.tag == qn("w:tbl"):
                self.issues.append(I.error(
                    "tables can't be typed; replace the table with tabs or plain paragraphs",
                    f"after paragraph {len(self.paragraphs)}"))
            elif el.tag == qn("w:sdt"):
                content = el.find(qn("w:sdtContent"))
                if content is not None:
                    self._walk_blocks(content)
            elif el.tag in (qn("w:customXml"), qn("w:ins")):
                self._walk_blocks(el)

    # -- paragraph properties

    def _paragraph(self, p_el):
        index = len(self.paragraphs) + 1
        chain = self.styles.ppr_chain(p_el)
        where = f"paragraph {index}"

        jc = _first(chain, "w:jc")
        jcv = jc.get(qn("w:val")) if jc is not None else "left"
        align = {"center": Align.CENTER, "right": Align.RIGHT, "end": Align.RIGHT,
                 "both": Align.JUSTIFY, "distribute": Align.JUSTIFY,
                 "lowKashida": Align.JUSTIFY, "mediumKashida": Align.JUSTIFY,
                 "highKashida": Align.JUSTIFY, "thaiDistribute": Align.JUSTIFY}.get(jcv, Align.LEFT)

        left = _attr_pt(chain, "w:ind", "w:left", "w:start") or 0.0
        right = _attr_pt(chain, "w:ind", "w:right", "w:end") or 0.0
        hanging = _attr_pt(chain, "w:ind", "w:hanging")
        first = -hanging if hanging else (_attr_pt(chain, "w:ind", "w:firstLine") or 0.0)

        before = _attr_pt(chain, "w:spacing", "w:before") or 0.0
        after = _attr_pt(chain, "w:spacing", "w:after") or 0.0

        tabs = []
        for el in reversed(chain):  # defaults first, own properties last
            t = el.find(qn("w:tabs"))
            if t is None:
                continue
            for tab in t.findall(qn("w:tab")):
                pos = int(tab.get(qn("w:pos"), "0")) / TWIPS_PER_PT
                kind = tab.get(qn("w:val"), "left")
                if kind == "clear":
                    tabs = [x for x in tabs if abs(x - pos) > 0.5]
                elif kind != "bar":
                    tabs.append(pos)
                    if kind not in ("left", "start", "num"):
                        self.note("tabkind", I.warning(
                            f"{kind} tab stops are treated as left tab stops", where))
        if _first(chain, "w:numPr") is not None:
            self.note("lists", I.warning(
                "list bullets/numbering aren't typed; type the numbers as text instead", where))

        para = Paragraph(
            spans=[], index=index, align=align,
            left_pt=left, right_pt=right, first_line_pt=first,
            space_before_pt=before, space_after_pt=after,
            keep_with_next=_on(_first(chain, "w:keepNext")),
            page_break_before=_on(_first(chain, "w:pageBreakBefore")),
            contextual_spacing=_on(_first(chain, "w:contextualSpacing")),
            style=self.styles.para_style_id(p_el),
            tab_stops_pt=tuple(sorted(set(tabs))),
            default_tab_pt=self.default_tab_pt,
        )
        self._p_el = p_el
        self._where = where
        self._spans: list[Span] = []
        self._fields: list[dict] = []  # stack of open complex fields
        self._content(p_el)
        para.spans = _merge_adjacent(split_placeholders(_merge_adjacent(self._spans)))
        self.paragraphs.append(para)

    # -- paragraph content

    def _content(self, parent):
        for el in parent.iterchildren():
            tag = el.tag
            if tag == qn("w:r"):
                self._run(el)
            elif tag == qn("w:fldSimple"):
                self._simple_field(el)
            elif tag in (qn("w:hyperlink"), qn("w:ins"), qn("w:smartTag"), qn("w:customXml"),
                         qn("w:moveTo"), qn("w:dir"), qn("w:bdo")):
                self._content(el)
            elif tag == qn("w:sdt"):
                content = el.find(qn("w:sdtContent"))
                if content is not None:
                    self._content(content)
            # w:del, w:moveFrom, w:pPr, bookmarks, proofing marks: nothing to type

    def _format(self, r_el) -> tuple[bool, bool, bool, bool]:
        """(bold, underline, uppercase, hidden) for a run."""
        chain = self.styles.rpr_chain(r_el, self._p_el)
        bold = _on(_first(chain, "w:b"))
        u = _first(chain, "w:u")
        underline = u is not None and u.get(qn("w:val"), "single") != "none"
        upper = _on(_first(chain, "w:caps")) or _on(_first(chain, "w:smallCaps"))
        hidden = _on(_first(chain, "w:vanish"))
        if _on(_first(chain, "w:i")):
            self.note("italic", I.info("italic is typed as plain text", self._where))
        if _on(_first(chain, "w:strike")) or _on(_first(chain, "w:dstrike")):
            self.note("strike", I.info("strikethrough is typed as plain text", self._where))
        return bold, underline, upper, hidden

    def _suppressing(self) -> bool:
        """Inside a field whose instruction or result we replace."""
        return any(f["phase"] == "instr" or not f["keep"] for f in self._fields)

    def _run(self, r_el):
        bold, underline, upper, hidden = self._format(r_el)
        for el in r_el.iterchildren():
            tag = el.tag
            if tag == qn("w:fldChar"):
                self._fld_char(el.get(qn("w:fldCharType")), bold, underline)
                continue
            if tag == qn("w:instrText"):
                if self._fields and self._fields[-1]["phase"] == "instr":
                    self._fields[-1]["instr"] += el.text or ""
                continue
            text = None
            if tag == qn("w:t"):
                text = el.text or ""
            elif tag == qn("w:tab"):
                text = "\t"
            elif tag == qn("w:br"):
                text = "\f" if el.get(qn("w:type")) == "page" else "\n"
            elif tag == qn("w:cr"):
                text = "\n"
            elif tag == qn("w:noBreakHyphen"):
                text = "-"
            elif tag == qn("w:sym"):
                self.note("sym", I.warning("symbol-font characters can't be typed and are left out",
                                           self._where))
            elif tag in (qn("w:drawing"), qn("w:pict"), qn("w:object")) and not self._suppressing():
                self.note(f"image{self._where}", I.error(
                    "images and text boxes can't be typed; remove them", self._where))
            if text is None or hidden:
                continue
            if self._fields:
                top = self._fields[-1]
                if top["phase"] == "result" and top["fmt"] is None and text.strip():
                    top["fmt"] = (bold, underline)
            if self._suppressing():
                continue
            if upper:
                text = text.upper()
            self._spans.append(Span(text, bold, underline))

    def _fld_char(self, kind, bold, underline):
        if kind == "begin":
            self._fields.append({"instr": "", "phase": "instr", "keep": False,
                                 "fmt": None, "begin_fmt": (bold, underline)})
        elif kind == "separate" and self._fields:
            f = self._fields[-1]
            f["phase"] = "result"
            ftype, _ = parse_field_instruction(f["instr"])
            f["keep"] = ftype in KEEP_RESULT_FIELDS
        elif kind == "end" and self._fields:
            f = self._fields.pop()
            outer_ok = not self._suppressing()
            if outer_ok:
                self._emit_field(f["instr"], f["fmt"] or f["begin_fmt"], f["keep"])

    def _emit_field(self, instr, fmt, result_kept):
        ftype, ref = parse_field_instruction(instr)
        if ref is not None:
            self._spans.append(Span(field=ref, bold=fmt[0], underline=fmt[1]))
        elif ftype in PAGE_FIELDS:
            self.note(f"page{self._where}", I.warning(
                "Word page-number fields are left out; turn on daisywriter's page numbers instead",
                self._where))
        elif ftype == "MERGEFIELD":
            self.issues.append(I.error("MERGEFIELD without a field name", self._where))
        elif ftype and ftype not in KEEP_RESULT_FIELDS:
            self.issues.append(I.error(
                f"Word {ftype} fields aren't supported; remove it or replace it with plain text",
                self._where))

    def _simple_field(self, el):
        instr = el.get(qn("w:instr"), "")
        ftype, _ = parse_field_instruction(instr)
        if ftype in KEEP_RESULT_FIELDS:
            self._content(el)
            return
        fmt = None
        for r in el.findall(qn("w:r")):
            b, u, _, _ = self._format(r)
            fmt = (b, u)
            break
        if not self._suppressing():
            self._emit_field(instr, fmt or (False, False), False)
